"""Markdown report. Values are wrapped in code spans so pipes and quotes stay literal."""

from __future__ import annotations

from reconlens.models import Finding, Report, SourceRun, iso, summarize


def render_markdown(report: Report) -> str:
    """Render a report as Markdown."""

    summary = summarize(report)
    target = report.target
    lines = [
        "# ReconLens report",
        "",
        f"- **Target:** {_code(target.value)}",
        f"- **Type:** {target.type.value}",
        f"- **Original input:** {_code(target.original)}",
        f"- **Started:** {iso(report.started_at)}",
        f"- **Finished:** {iso(report.finished_at)}",
        f"- **Elapsed:** {summary.elapsed_ms} ms",
        f"- **Tool:** reconlens {report.tool_version}",
        "",
        "Passive reconnaissance only. This report does not include port scans, "
        "name guessing, or login attempts.",
        "",
        "## Summary",
        "",
        "| Source | Status | Findings | Duration |",
        "| --- | --- | --- | --- |",
    ]
    for source in report.sources:
        lines.append(
            "| "
            + " | ".join(
                (
                    _cell(source.name),
                    source.status,
                    str(len(source.findings)),
                    f"{source.duration_ms} ms",
                )
            )
            + " |"
        )
    lines.extend(
        [
            "",
            f"- Sources ok: {summary.ok}",
            f"- Sources skipped: {summary.skipped}",
            f"- Sources failed: {summary.errors}",
            f"- Findings: {summary.findings}",
            "",
        ]
    )
    if report.notices:
        lines.extend(["## Notices", ""])
        lines.extend(f"- {_text(notice)}" for notice in report.notices)
        lines.append("")
    for source in report.sources:
        lines.extend(_source_section(source))
    lines.append(
        "_Generated by ReconLens. Use the underlying records only for work you are authorized to do._"
    )
    lines.append("")
    return "\n".join(lines)


def _source_section(source: SourceRun) -> list[str]:
    lines = [f"## {source.name}", ""]
    if source.status == "skipped":
        lines.append(f"Skipped. {_text(source.skip_reason or 'No reason recorded.')}")
        lines.append("")
        return lines
    if source.status == "error":
        lines.append(f"Failed. {_text(source.error or 'No error recorded.')}")
        lines.append("")
        return lines
    if source.cached:
        lines.append("_Served from the local cache._")
        lines.append("")
    if not source.findings:
        lines.append("No findings.")
        lines.append("")
        return lines
    for finding in source.findings:
        lines.extend(_finding_block(finding))
    return lines


def _finding_block(finding: Finding) -> list[str]:
    lines = [
        f"### {_text(finding.title)}",
        "",
        f"- **Value:** {_code(finding.value)}",
        f"- **Severity:** {finding.severity.value}",
        f"- **Category:** {finding.category}",
        f"- **Observed:** {iso(finding.timestamp)}",
    ]
    if finding.detail:
        lines.append(f"- **Detail:** {_text(finding.detail)}")
    if finding.source_url:
        lines.append(f"- **Reference:** {_text(finding.source_url)}")
    if finding.data:
        rendered = ", ".join(f"{key}={value}" for key, value in finding.data.items())
        lines.append(f"- **Data:** {_code(rendered)}")
    lines.append("")
    return lines


def _code(value: str) -> str:
    return "`" + value.replace("`", "'") + "`"


def _text(value: str) -> str:
    return value.replace("\r", " ").replace("\n", " ")


def _cell(value: str) -> str:
    return _text(value).replace("|", "\\|")
