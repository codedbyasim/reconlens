def render_html(report: Report) -> str:
    """Render a single HTML document with the stylesheet inlined."""

    summary = summarize(report)
    target = html.escape(report.target.value)
    body = [
        "<!DOCTYPE html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        f"<title>ReconLens report: {target}</title>",
        f"<style>{_CSS}</style>",
        "</head>",
        "<body>",
        '<p class="skip"><a href="#report">Skip to report</a></p>',
        '<main class="wrap" id="report">',
        _header(report),
        _stats(summary),
        _source_table(report),
        _notices(report),
    ]
    for source in report.sources:
        body.append(_source_section(source))
    body.extend(
        [
            "<footer>",
            "Generated by ReconLens. Passive reconnaissance only: no port scans, "
            "name guessing, or login attempts. Use this report only for work you "
            "are authorized to do.",
            "</footer>",
            "</main>",
            "</body>",
            "</html>",
            "",
        ]
    )
    return "\n".join(body)


def _header(report: Report) -> str:
    summary = summarize(report)
    return "\n".join(
        [
            '<header class="top">',
            _logo(),
            "<div>",
            (
                f'<p class="eyebrow">ReconLens {html.escape(report.tool_version)}'
                " · passive report</p>"
            ),
            f"<h1>{html.escape(report.target.value)}</h1>",
            (
                '<p class="meta">'
                f"{html.escape(report.target.type.value)} · "
                f"{html.escape(iso(report.started_at))} · "
                f"{summary.elapsed_ms} ms"
                "</p>"
            ),
            "</div>",
            "</header>",
        ]
    )


def _stats(summary: Summary) -> str:
    cells = (
        (str(summary.ok), "sources ok"),
        (str(summary.skipped), "skipped"),
        (str(summary.errors), "failed"),
        (str(summary.findings), "findings"),
    )
    parts = ['<section class="stats" aria-label="Summary">']
    for number, label in cells:
        parts.append(
            f'<div class="stat"><b>{html.escape(number)}</b><span>{html.escape(label)}</span></div>'
        )
    parts.append("</section>")
    return "\n".join(parts)


def _source_table(report: Report) -> str:
    rows = [
        "<section>",
        "<h2>Sources</h2>",
        "<table>",
        "<thead><tr><th>Source</th><th>Status</th><th>Findings</th><th>Duration</th></tr></thead>",
        "<tbody>",
    ]
    for source in report.sources:
        rows.append(
            "<tr>"
            f"<td>{html.escape(source.name)}</td>"
            f'<td class="status-{html.escape(source.status)}">{html.escape(source.status)}</td>'
            f"<td>{len(source.findings)}</td>"
            f"<td>{source.duration_ms} ms</td>"
            "</tr>"
        )
    rows.extend(["</tbody>", "</table>", "</section>"])
    return "\n".join(rows)


def _notices(report: Report) -> str:
    if not report.notices:
        return ""
    items = "".join(f"<li>{html.escape(notice)}</li>" for notice in report.notices)
    return f"<section><h2>Notices</h2><ul>{items}</ul></section>"


def _source_section(source: SourceRun) -> str:
    parts = ["<section>", f"<h2>{html.escape(source.name)}</h2>"]
    if source.status == "skipped":
        reason = source.skip_reason or "No reason recorded."
        parts.append(f'<p class="note">Skipped. {html.escape(reason)}</p></section>')
        return "\n".join(parts)
    if source.status == "error":
        reason = source.error or "No error recorded."
        parts.append(f'<p class="note">Failed. {html.escape(reason)}</p></section>')
        return "\n".join(parts)
    if source.cached:
        parts.append('<p class="note">Served from the local cache.</p>')
    if not source.findings:
        parts.append('<p class="note">No findings.</p></section>')
        return "\n".join(parts)
    for finding in source.findings:
        parts.append(_finding_card(finding))
    parts.append("</section>")
    return "\n".join(parts)


def _finding_card(finding: Finding) -> str:
    severity = html.escape(finding.severity.value)
    bits = [
        f'<article class="sev-{severity}">',
        "<h3>",
        html.escape(finding.title),
        f'<span class="badge">{severity}</span>',
        "</h3>",
        f'<p class="value">{html.escape(finding.value)}</p>',
    ]
    if finding.detail:
        bits.append(f'<p class="detail">{html.escape(finding.detail)}</p>')
    href = _href(finding.source_url)
    if href:
        bits.append(
            f'<p class="ref"><a href="{href}">{html.escape(finding.source_url or "")}</a></p>'
        )
    bits.append("</article>")
    return "".join(bits)


def _href(url: str | None) -> str | None:
    if not url:
        return None
    parts = urlsplit(url)
    if parts.scheme not in {"http", "https"} or not parts.netloc:
        return None
    return html.escape(url, quote=True)


